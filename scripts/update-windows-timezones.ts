const CLDR_REF_PATTERN = /^[\w.-]+$/;
const WORLD_MAPPING_PATTERN = /<mapZone other="([^"]+)" territory="001" type="([^"]+)"\/>/g;
const OUTPUT_FILE = new URL("../packages/calendar/src/ics/utils/windows-timezones.ts", import.meta.url);

const ref = process.argv[2];
if (!ref || !CLDR_REF_PATTERN.test(ref)) {
  console.error("Usage: bun scripts/update-windows-timezones.ts <unicode-org/cldr git ref, e.g. a commit SHA>");
  process.exit(1);
}

const url = `https://raw.githubusercontent.com/unicode-org/cldr/${ref}/common/supplemental/windowsZones.xml`;
const response = await fetch(url);
if (!response.ok) {
  throw new Error(`${url} answered ${response.status}`);
}

const windowsZonesXml = await response.text();
const mappings = [...windowsZonesXml.matchAll(WORLD_MAPPING_PATTERN)]
  .map(([, windowsTimeZone, ianaTimeZone]) => [windowsTimeZone, ianaTimeZone])
  .toSorted(([left = ""], [right = ""]) => Number(left > right) - Number(left < right));
if (mappings.length === 0) {
  throw new Error(`${url} has no territory 001 mappings`);
}

const entries = mappings.map(([windowsTimeZone, ianaTimeZone]) => `  ${JSON.stringify(windowsTimeZone)}: ${JSON.stringify(ianaTimeZone)},`);
await Bun.write(OUTPUT_FILE, [
  `// Generated by scripts/update-windows-timezones.ts from unicode-org/cldr ${ref}; do not edit.`,
  "const WINDOWS_TO_IANA: Record<string, string> = {",
  ...entries,
  "};",
  "",
  "export { WINDOWS_TO_IANA };",
  "",
].join("\n"));
console.log(`Windows timezone mappings updated to CLDR ${ref} (${mappings.length} zones)`);
