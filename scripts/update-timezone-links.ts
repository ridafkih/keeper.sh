const TZDB_VERSION_PATTERN = /^\d{4}[a-z]$/;
const TZDB_SOURCE_FILES = [
  "africa",
  "antarctica",
  "asia",
  "australasia",
  "backward",
  "etcetera",
  "europe",
  "northamerica",
  "southamerica",
];
const LINK_LINE_PATTERN = /^Link\s+(\S+)\s+(\S+)/;
const OUTPUT_FILE = new URL("../packages/calendar/src/ics/utils/timezone-links.ts", import.meta.url);

const version = process.argv[2];
if (!version || !TZDB_VERSION_PATTERN.test(version)) {
  console.error("Usage: bun scripts/update-timezone-links.ts <tzdb version, e.g. 2026f>");
  process.exit(1);
}

const downloadSourceFile = async (fileName: string): Promise<string> => {
  const url = `https://raw.githubusercontent.com/eggert/tz/${version}/${fileName}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} answered ${response.status}`);
  }
  return await response.text();
};

const readLinks = (source: string): [string, string][] =>
  source.split("\n").flatMap((line): [string, string][] => {
    const match = LINK_LINE_PATTERN.exec(line);
    if (!match?.[1] || !match[2]) {
      return [];
    }
    return [[match[2], match[1]]];
  });

const followLink = (links: Map<string, string>, name: string): string => {
  const visited = new Set<string>();
  let current = name;
  while (links.has(current) && !visited.has(current)) {
    visited.add(current);
    current = links.get(current) ?? current;
  }
  return current;
};

const sources = await Promise.all(TZDB_SOURCE_FILES.map((fileName) => downloadSourceFile(fileName)));
const links = new Map(sources.flatMap((source) => readLinks(source)));
if (links.size === 0) {
  throw new Error(`tzdb ${version} has no links`);
}

const entries = [...links.keys()]
  .toSorted((left, right) => Number(left > right) - Number(left < right))
  .map((link) => `  ${JSON.stringify(link)}: ${JSON.stringify(followLink(links, link))},`);
await Bun.write(OUTPUT_FILE, [
  `// Generated by scripts/update-timezone-links.ts from tzdb ${version}; do not edit.`,
  `const TIMEZONE_LINKS_TZDB_VERSION = ${JSON.stringify(version)};`,
  "",
  "const IANA_LINK_TARGETS: Record<string, string> = {",
  ...entries,
  "};",
  "",
  "export { IANA_LINK_TARGETS, TIMEZONE_LINKS_TZDB_VERSION };",
  "",
].join("\n"));
console.log(`IANA timezone links updated to tzdb ${version} (${links.size} links)`);
